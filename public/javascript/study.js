const parseMarkdown = (markdown, headingIndex = 0, html = `<div class="markdownContainer">`, inList = false, inCodeBlock = false, codeBuffer = []) => {
	const formatInline = text =>
		text.replace(/`([^`]+)`/g, '<code class="md-inline-code">$1</code>')
			.replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
			.replace(/\*([^*]+)\*/g, '<em>$1</em>')
			.replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2" target="_blank" class="md-link">$1</a>');
	const lines = markdown.split('\n');
	for (let line of lines) {
		if (/^```/.test(line)) {
			inCodeBlock = !inCodeBlock;
			if (!inCodeBlock) {
				html += `<pre><code>${codeBuffer.join('\n')}</code></pre>`;
				codeBuffer = [];
			}
			continue;
		}
		if (inCodeBlock) {
			codeBuffer.push(line);
			continue;
		} else if (!inCodeBlock) {
			line = line.replace(/\t/g, ''); // Remove all tab characters outside code blocks
		}
		if (/^#\s/.test(line)) {
			const content = formatInline(line.replace(/^#\s/, ''));
			html += `<h1 class="md-h1">${content}</h1>`;
		} else if (/^##\s/.test(line)) {
			const content = formatInline(line.replace(/^##\s/, ''));
			html += `<h2 class="md-h2">${content}</h2>`;
		} else if (/^###\s/.test(line)) {
			const content = formatInline(line.replace(/^###\s/, ''));
			html += `<h3 class="md-h3">${content}</h3>`;
		} else if (/^####\s/.test(line)) {
			headingIndex++;
			const title = formatInline(line.replace(/^####\s/, ''));
			html += `<h4 id="section-${headingIndex}" class="md-h4">${title}</h4>`;
		} else if (/^---$/.test(line)) html += `<hr class="md-hr">`;
		else if (/^>\s/.test(line)) html += `<blockquote class="md-blockquote">${formatInline(line.replace(/^>\s/, ''))}</blockquote>`;
		else if (/^(\*|\-|\d+\.)\s/.test(line)) {
			if (!inList) {
				html += `<ul class="md-list">`;
				inList = true;
			}
			const item = formatInline(line.replace(/^(\*|\-|\d+\.)\s/, ''));
			html += `<li class="md-list-item">${item}</li>`;
		} else {
			if (inList) {
				html += `</ul>`;
				inList = false;
			}
			const formatted = formatInline(line);
			if (formatted.trim()) html += `<p class="md-paragraph">${formatted}</p>`;
		}
	}
	if (inList) html += `</ul>`;
	html += `</div>`;
	return html;
};

